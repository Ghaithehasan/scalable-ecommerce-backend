import * as grpc from '@grpc/grpc-js';
import * as protoLoader from '@grpc/proto-loader';
import {
  Injectable,
  Logger,
  OnModuleDestroy,
  OnModuleInit,
} from '@nestjs/common';

import type {
  GetStockResponse,
  ReleaseStockResponse,
  ReserveStockResponse,
} from './generated/inventory/v1/inventory';
import {
  inventoryGrpcUrl,
  readTimeoutMs,
  releaseTimeoutMs,
  reserveTimeoutMs,
  resolveInventoryProtoPath,
  resolveProtoDir,
} from './inventory.config';
import { isInventoryUnreachable } from './inventory.errors';

export interface ReserveItemInput {
  /** The catalogue id, converted to the string the contract uses. */
  productId: string;
  quantity: number;
}

export interface StockLevel {
  available: number;
  reserved: number;
}

/**
 * The application's door to the warehouse.
 *
 * It owns one gRPC channel for the whole process, puts a deadline on every
 * call, and never lets a gRPC concept leak upwards: callers get plain values
 * or exceptions they can map to HTTP.
 */
@Injectable()
export class InventoryClient implements OnModuleInit, OnModuleDestroy {
  private readonly logger = new Logger(InventoryClient.name);
  private client?: grpc.Client;

  onModuleInit(): void {
    const protoPath = resolveInventoryProtoPath();
    const url = inventoryGrpcUrl();

    const definition = protoLoader.loadSync(protoPath, {
      // Must match the server's loader options, or field names differ on the
      // two sides of the wire.
      keepCase: false,
      defaults: true,
      oneofs: true,
      includeDirs: [resolveProtoDir()],
    });

    const pkg = grpc.loadPackageDefinition(definition) as unknown as {
      inventory: { v1: { InventoryService: grpc.ServiceClientConstructor } };
    };

    this.client = new pkg.inventory.v1.InventoryService(
      url,
      grpc.credentials.createInsecure(),
    );

    // Creating the channel does not connect; the first call does. That is
    // intentional - the application must start even when the warehouse is
    // down, and simply refuse orders until it returns.
    this.logger.log(`Inventory gRPC client configured for ${url}`);
  }

  onModuleDestroy(): void {
    this.client?.close();
  }

  /**
   * Current levels for a batch of products.
   *
   * Returns an empty map rather than throwing when the warehouse cannot be
   * reached: a catalogue page should still render, just without quantities.
   * Order placement never relies on this - it reserves, which is atomic.
   */
  async getStock(productIds: string[]): Promise<Map<string, StockLevel>> {
    if (productIds.length === 0) {
      return new Map();
    }

    try {
      const response = await this.call<GetStockResponse>(
        'GetStock',
        { productIds },
        readTimeoutMs(),
      );

      return new Map(
        response.items.map((item) => [
          item.productId,
          { available: item.available, reserved: item.reserved },
        ]),
      );
    } catch (error) {
      if (isInventoryUnreachable(error)) {
        this.logger.warn(
          `Inventory unavailable while reading stock; serving the catalogue without quantities`,
        );
        return new Map();
      }

      throw error;
    }
  }

  /**
   * Checks and reserves every item in one call.
   *
   * `reservationId` is generated by US, before the call, so a retry or a
   * compensating release always refers to the same reservation.
   */
  reserveStock(
    reservationId: string,
    items: ReserveItemInput[],
  ): Promise<ReserveStockResponse> {
    return this.call<ReserveStockResponse>(
      'ReserveStock',
      { reservationId, items },
      reserveTimeoutMs(),
    );
  }

  /** Compensation. Safe to call for a reservation that never happened. */
  releaseStock(reservationId: string): Promise<ReleaseStockResponse> {
    return this.call<ReleaseStockResponse>(
      'ReleaseStock',
      { reservationId },
      releaseTimeoutMs(),
    );
  }

  private call<T>(
    method: string,
    payload: unknown,
    timeoutMs: number,
  ): Promise<T> {
    const client = this.client;

    if (!client) {
      return Promise.reject(new Error('Inventory client is not initialised'));
    }

    return new Promise<T>((resolve, reject) => {
      (client as unknown as Record<string, Function>)[method](
        payload,
        { deadline: new Date(Date.now() + timeoutMs) },
        (error: grpc.ServiceError | null, value: T) => {
          if (error) {
            reject(error);
            return;
          }
          resolve(value);
        },
      );
    });
  }
}
